def build_full():
    spec = build_main()
    spec["slides"] = MAIN + APPENDIX
    return spec


def main():
    check_only = "--check" in sys.argv
    os.makedirs(SPEC_DIR, exist_ok=True)
    for name, spec in [("PPT_烯烃复分解.pptx", build_main()),
                       ("PPT_烯烃复分解_问题作答版.pptx", build_full())]:
        out = os.path.join(BASE, name)
        first_spec = os.path.join(SPEC_DIR, os.path.splitext(name)[0] + ".json")
        print("=" * 70)
        print(name, f"({len(spec['slides'])} 页)")
        kit.run(spec, out, check_only=check_only, spec_path=first_spec)
        if not check_only:
            import json
            s2 = json.loads(json.dumps(spec))
            for s in s2["slides"]:
                if s.get("img", "").startswith("../"):
                    s["img"] = s["img"][3:]
            work = os.path.join(BASE, os.path.splitext(name)[0] + ".spec.json")
            with open(work, "w", encoding="utf-8") as fh:
                json.dump(s2, fh, ensure_ascii=False, indent=1)
            print("spec ->", work)


if __name__ == "__main__":
    main()











